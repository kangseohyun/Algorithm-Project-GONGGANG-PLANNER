def normalize_place_name(place_name):
    """Return the standard place name when an alias is known."""
    if place_name in PLACE_ALIASES:
        return PLACE_ALIASES[place_name]
    return place_name


def get_recommendation_places(include_support=False):
    """Return places used by the recommendation feature."""
    if include_support:
        result = dict(RECOMMENDATION_PLACES)
        result.update(SUPPORT_PLACES)
        return result
    return RECOMMENDATION_PLACES


def get_recommendation_evidence(place_name):
    """Return the recommendation evidence for a place."""
    standard_name = normalize_place_name(place_name)
    return RECOMMENDATION_EVIDENCE.get(standard_name, {})
